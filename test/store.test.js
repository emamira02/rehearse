import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { createStore, CONSENT_VERSION, MAX_RECORD_BYTES } = require('../electron/store.cjs');

const made = [];
const tmp = () => { const d = fs.mkdtempSync(path.join(os.tmpdir(), 'rehearse-store-')); made.push(d); return d; };
after(() => { for (const d of made) fs.rmSync(d, { recursive: true, force: true }); });
const rec = (over = {}) => ({ title: 'Talk', mode: 'live', durationS: 60, summary: { durationS: 59 }, timeline: { segments: [] }, ...over });

test('consent: absent by default, versioned, preferences kept', () => {
  const st = createStore(tmp());
  assert.equal(st.hasConsent(), false);
  const s = st.giveConsent({ pulseEnabled: true });
  assert.equal(s.consentVersion, CONSENT_VERSION);
  assert.equal(st.hasConsent(), true);
  assert.equal(st.getSettings().pulseEnabled, true);
  st.updateSettings({ pulseEnabled: false, nudges: false, consentVersion: 99 });   // consent cannot be forged here
  assert.equal(st.getSettings().consentVersion, CONSENT_VERSION);
  assert.equal(st.getSettings().pulseEnabled, false);
  assert.equal(st.getSettings().nudges, false);
});

test('save/list/get/remove round trip; ids generated by the store', () => {
  const st = createStore(tmp());
  const a = st.save(rec({ title: '  First \n talk ', id: '../../evil' }));
  const b = st.save(rec({ title: 'Second', mode: 'weird' }));
  assert.match(a.id, /^\d{8}-\d{6}-[a-f0-9]{6}$/);
  assert.equal(a.title, 'First   talk');
  assert.equal(st.get(b.id).mode, 'simulated');        // unknown mode never claims to be live
  const { items, unreadable } = st.list();
  assert.equal(items.length, 2);
  assert.equal(unreadable, 0);
  assert.equal(items[0].timeline, undefined);           // list is light
  assert.equal(st.remove(a.id), true);
  assert.equal(st.remove(a.id), false);
  assert.equal(st.list().items.length, 1);
});

test('only whitelisted fields reach the disk', () => {
  const st = createStore(tmp());
  const saved = st.save(rec({ frame: 'x'.repeat(100), apiKey: 'secret' }));
  const raw = fs.readFileSync(path.join(st.dir, `${saved.id}.json`), 'utf8');
  assert.ok(!raw.includes('secret') && !raw.includes('frame'));
});

test('rejects bad ids, bad shapes and oversized records', () => {
  const st = createStore(tmp());
  for (const id of ['../settings', '..\\x', '20261112-120000-abcdeg', '', null, 42]) {
    assert.throws(() => st.get(id), RangeError);
    assert.throws(() => st.remove(id), RangeError);
  }
  assert.throws(() => st.save(null), TypeError);
  assert.throws(() => st.save({ summary: {} }), TypeError);
  assert.throws(() => st.save(rec({ timeline: { big: 'x'.repeat(MAX_RECORD_BYTES) } })), RangeError);
});

test('corrupt files are skipped and reported; removeAll wipes everything incl. leftovers and consent', () => {
  const st = createStore(tmp());
  st.giveConsent();
  st.save(rec());
  fs.writeFileSync(path.join(st.dir, '20260101-000000-abcdef.json'), '{not json');
  fs.writeFileSync(path.join(st.dir, 'stray.tmp'), 'x');
  const { items, unreadable } = st.list();
  assert.equal(items.length, 1);
  assert.equal(unreadable, 1);
  const res = st.removeAll();
  assert.equal(res.removed, 2);
  assert.equal(fs.existsSync(st.dir), false);
  assert.equal(st.hasConsent(), false);
  assert.deepEqual(st.list(), { items: [], unreadable: 0 });
});
